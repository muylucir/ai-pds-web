# backend/tests/test_routes_account.py
#
# The route layer for changing one's own password (POST /me/password). It verifies three things:
#
#   1) The request's access token goes to Cognito as is — this path is not an Admin* call
#      but a self-service API **authorized by the token itself**, so there is structurally no way
#      to change another user's password. The token is the identity.
#   2) Cognito error codes → HTTP status + stable error code. The mapping here is
#      **different** from admin_users.py: the one who chose the value is the user, not the server.
#   3) It does not silently pass in local development with auth not configured.
from __future__ import annotations

import pytest
from fastapi.testclient import TestClient

import aipds.app as app_module
from aipds import error_codes as ec
from aipds.auth.cognito import CognitoError
from aipds.auth.deps import require_user
from aipds.auth.models import Principal

ME = Principal(username="pm", sub="s-pm", role="pm")
# The `nosec` markers in this file all say the same thing: these are fixture
# strings for a route that forwards passwords to a stubbed Cognito client. The
# token is three words with dots in it, and the passwords exist to be asserted
# on. None of them opens anything.
TOKEN = "header.payload.signature"  # nosec B105
AUTH = {"Authorization": f"Bearer {TOKEN}"}
BODY = {"current_password": "OldPass1!", "new_password": "NewPass2@"}  # nosec B105


class FakeIdp:
    """Stand-in for the cognito-idp client. Accepts only change_password calls."""

    def __init__(self) -> None:
        self.calls: list[dict] = []
        self.error: CognitoError | None = None

    def change_password(self, **params):
        self.calls.append(params)
        if self.error is not None:
            raise self.error
        return {"ResponseMetadata": {"HTTPStatusCode": 200}}


@pytest.fixture()
def idp(monkeypatch):
    fake = FakeIdp()
    # This route works only in "a deployment with Cognito configured" — if not configured it refuses
    # explicitly with 503 (the last test). So the configured state must be imitated.
    monkeypatch.setattr(
        app_module, "cognito_config",
        lambda: {"region": "ap-northeast-2",
                 "user_pool_id": "ap-northeast-2_TEST123",
                 "client_id": "testclientid"})
    monkeypatch.setattr(app_module, "cognito_idp_client", lambda: fake)
    app_module.app.dependency_overrides[require_user] = lambda: ME
    yield fake
    app_module.app.dependency_overrides.clear()


@pytest.fixture()
def client():
    return TestClient(app_module.app)


def _fail_with(idp: FakeIdp, code: str) -> None:
    idp.error = CognitoError(code, f"stubbed {code}")


# ---- Success path ----

def test_the_request_access_token_is_what_authorizes_the_change(idp, client):
    r = client.post("/me/password", json=BODY, headers=AUTH)
    assert r.status_code == 204, r.text
    assert len(idp.calls) == 1
    call = idp.calls[0]
    # The token must be exactly as it came in the request. If some other credential the server holds
    # slipped in here, the guarantee that "you only change your own" would be gone.
    assert call["AccessToken"] == TOKEN
    assert call["PreviousPassword"] == BODY["current_password"]
    assert call["ProposedPassword"] == BODY["new_password"]
    # Username/pool id are not passed — this API does not accept them.
    assert "Username" not in call
    assert "UserPoolId" not in call


def test_nothing_of_the_password_comes_back_in_the_response(idp, client):
    r = client.post("/me/password", json=BODY, headers=AUTH)
    assert r.status_code == 204
    assert r.content == b""


# ---- Error translation ----

def test_a_wrong_current_password_is_400_with_its_own_code(idp, client):
    # Cognito raises NotAuthorizedException when the current password is wrong.
    # admin_users.py translates that code into 403/forbidden, but doing that here
    # would make the screen say "권한이 없습니다" (you do not have permission) — the user does have
    # permission over their own account; what is wrong is the value they entered.
    _fail_with(idp, "NotAuthorizedException")
    r = client.post("/me/password", json=BODY, headers=AUTH)
    assert r.status_code == 400
    assert r.json()["detail"] == ec.WRONG_PASSWORD


def test_a_policy_violating_new_password_is_400_not_500(idp, client):
    # admin_users.py treats InvalidPasswordException as 500 — there the value was
    # generated by the server, so failing the policy is our defect. Here the value was
    # chosen by the user, so it is 400, and the screen must be able to explain the policy again.
    _fail_with(idp, "InvalidPasswordException")
    r = client.post("/me/password", json=BODY, headers=AUTH)
    assert r.status_code == 400
    assert r.json()["detail"] == ec.PASSWORD_POLICY


def test_too_many_attempts_is_429(idp, client):
    # Cognito limits the number of attempts. Collapsing it into 502 would make the screen say "server error",
    # when what the user should do is wait a moment.
    _fail_with(idp, "LimitExceededException")
    r = client.post("/me/password", json=BODY, headers=AUTH)
    assert r.status_code == 429
    assert r.json()["detail"] == ec.TOO_MANY_REQUESTS


def test_throttling_is_also_429(idp, client):
    _fail_with(idp, "TooManyRequestsException")
    r = client.post("/me/password", json=BODY, headers=AUTH)
    assert r.status_code == 429


def test_a_token_without_the_self_service_scope_asks_for_reauth(idp, client):
    """A missing scope must not show up as "the current password is wrong".

    Cognito raises `NotAuthorizedException` in both cases — they cannot be told apart by code alone,
    only by message. The distinction matters because what the user must do is the
    opposite: a user holding a token without the scope gets "the current password is wrong"
    no matter what they enter, while what they actually need to do is log in again.
    """
    idp.error = CognitoError(
        "NotAuthorizedException",
        "Access Token does not have required scopes")
    r = client.post("/me/password", json=BODY, headers=AUTH)
    assert r.status_code == 403
    assert r.json()["detail"] == ec.REAUTH_REQUIRED


def test_an_unknown_cognito_code_is_502(idp, client):
    _fail_with(idp, "InternalErrorException")
    r = client.post("/me/password", json=BODY, headers=AUTH)
    assert r.status_code == 502
    assert r.json()["detail"] == ec.PASSWORD_CHANGE_FAILED


# ---- Input validation ----

def test_a_missing_new_password_never_reaches_cognito(idp, client):
    r = client.post("/me/password",
                    json={"current_password": "OldPass1!"},  # nosec B105
                    headers=AUTH)
    assert r.status_code == 422
    assert idp.calls == []


def test_an_empty_new_password_never_reaches_cognito(idp, client):
    r = client.post("/me/password",
                    json={"current_password": "OldPass1!",  # nosec B105
                          "new_password": ""},
                    headers=AUTH)
    assert r.status_code == 422
    assert idp.calls == []


# ---- When there is no token ----

def test_without_a_bearer_token_the_call_is_401_not_a_crash(idp, client):
    # Even if require_user is overridden and passes, this route separately needs the **raw token**.
    # Without it there is nothing to send to Cognito — crashing here
    # with a 500 would make the cause look like "a configuration problem".
    r = client.post("/me/password", json=BODY)
    assert r.status_code == 401
    assert idp.calls == []


def test_local_dev_without_cognito_refuses_explicitly(monkeypatch, client):
    # Locally with auth not configured, require_user lets everything through as a virtual admin.
    # If this route silently returned 200 in that state, it would give the user a false
    # confirmation that "the password was changed".
    monkeypatch.setattr(app_module, "cognito_config", lambda: None)
    app_module.app.dependency_overrides[require_user] = lambda: ME
    try:
        r = client.post("/me/password", json=BODY, headers=AUTH)
        assert r.status_code == 503
        assert r.json()["detail"] == ec.AUTH_NOT_CONFIGURED
    finally:
        app_module.app.dependency_overrides.clear()
